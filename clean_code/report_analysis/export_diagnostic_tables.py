"""Export LaTeX table rows from the archived diagnostics and experiment results."""

import argparse
import json
from pathlib import Path

import pandas as pd


MODELS = {"dt": "Decision Tree", "rf": "Random Forest", "hgb": r"HistGradient\-Boosting"}
SPLIT_SETS = (("RAND", "flow"), ("RAND", "flow+id"), ("GRP", "flow"), ("GRP", "flow+id"))
CONTRAST_NAMES = {
    "past_minus_flow": "Quá khứ trừ chỉ luồng",
    "past_minus_shuffled": "Quá khứ trừ hoán vị",
    "all_minus_past": "Toàn tập trừ quá khứ",
    "identity_minus_flow": "Thêm danh tính",
}


def count(n):
    return f"{int(n):,}".replace(",", ".")


def decimal(x):
    return f"{x:.2f}".replace(".", ",")


def signed(x):
    return r"\(" + f"{x:+.2f}".replace(".", "{,}") + r"\)"


def send_rows(folder, name, rows):
    lines = ["% Generated by export_diagnostic_tables.py"]
    lines.extend(" & ".join(row) + r" \\" for row in rows)
    (folder / f"{name}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def dataset_rows(artifacts, provenance, output):
    eda = json.loads((artifacts / "eda/dataset_summary.json").read_bytes())
    diagnostic = json.loads((artifacts / "eda/feature_diagnostics.json").read_bytes())
    classes = eda["cse_cic"]["classes"]
    before, after = provenance["class_counts_reference_subset"], provenance["class_counts"]
    send_rows(output, "recovery_cse", [
        (c, count(before[c]), count(after[c]), count(before[c] - after[c]), decimal(100 * after[c] / before[c]))
        for c in classes
    ])
    send_rows(output, "cse_by_day", [
        (day, *(count(n) for n in counts)) for day, counts in eda["cse_cic"]["by_day"].items()
    ])
    for dataset, record in eda.items():
        support = record["time_split"]["table"]
        send_rows(output, f"time_{dataset}", [
            (c, *(count(support[split][i]) for split in ("train", "val", "test")))
            for i, c in enumerate(record["classes"])
        ])
        counts = diagnostic[dataset]["test_overlap_with_benign_by_class"]
        confusion = diagnostic[dataset]["confusion_matrix"]
        send_rows(output, f"overlap_{dataset}", [
            (c, count(n), count(record["overlap_counts"][i]), count(counts[i]),
             decimal(100 * counts[i] / n), count(confusion[i][0]))
            for i, (c, n) in enumerate(zip(record["classes"], record["test_by_class"]))
        ])
    return eda


def model_rows(artifacts, eda, output):
    execution = []
    for dataset, record in eda.items():
        obj = json.loads((artifacts / f"reproduction/{dataset}/resacag/metrics.json").read_bytes())
        rates = sorted(obj["noise"], key=float)
        send_rows(output, f"noise_{dataset}", [
            (c, *(decimal(100 * obj["noise"][rate]["per_class"][c]["recall"]) for rate in rates))
            for c in record["classes"]
        ])
        execution.append(({"darknet": "CIC-DarkNet", "cse_cic": "CSE-CIC"}[dataset],
                          "CUDA" if obj["gpu_peak_allocated_mib"] else "CPU",
                          count(obj["epochs_completed"]), count(obj["parameters"]),
                          decimal(obj["train_validation_seconds"]), decimal(obj["test_seconds"]),
                          decimal(obj["process_peak_rss_mib_sampled"])))
    send_rows(output, "execution", execution)

    rows = pd.read_csv(artifacts / "source_ip/metrics.csv")
    for model in MODELS:
        m = rows[rows["model"] == model].groupby(["split", "set"]).mean(numeric_only=True)
        send_rows(output, f"e9_recall_{model}", [
            (c, *(decimal(100 * m.loc[group, f"recall_{i}"]) for group in SPLIT_SETS))
            for i, c in enumerate(eda["cse_cic"]["classes"])
        ])
    flow = rows[rows["set"] == "flow"].pivot(index="seed", columns=["model", "split"], values="macro_f1")
    send_rows(output, "e9_seeds", [
        (str(seed), *(decimal(100 * row[model, split]) for model in MODELS for split in ("RAND", "GRP")))
        for seed, row in flow.iterrows()
    ])
    pairs = []
    for seed in range(42, 47):
        a, b = [json.loads((artifacts / f"lab6/runs/{exp}/seed_{seed}/resacag/metrics.json").read_bytes())
                ["test"]["f1_macro"] for exp in ("E6", "E5")]
        pairs.append((str(seed), decimal(100 * a), decimal(100 * b), signed(100 * (b - a))))
    send_rows(output, "node2vec_seeds", pairs)


def configuration_rows(artifacts, output):
    lookup = pd.read_csv(artifacts / "source_ip/configurations/summary.csv").set_index(["model", "contrast"])
    configs = ("C00", "C01", "C10", "C11")
    send_rows(output, "ip_configs", [
        (label, *(signed(lookup.loc[(name, "past_minus_flow"), cfg]) for cfg in configs))
        for name, label in MODELS.items()
    ])
    rows = []
    for contrast, title in CONTRAST_NAMES.items():
        for name, label in MODELS.items():
            item = lookup.loc[name, contrast]
            interval = r"\left[" + f"{item.wide_lo:+.2f};\\ {item.wide_hi:+.2f}".replace(".", "{,}") + r"\right]"
            rows.append((title, label, signed(item.mean_pp), r"\(" + interval + r"\)",
                         f"{int(item.configs_improved)}/4"))
    send_rows(output, "ip_config_contrasts", rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("artifacts", type=Path)
    parser.add_argument("cse_provenance", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    provenance = json.loads(args.cse_provenance.read_bytes())
    eda = dataset_rows(args.artifacts, provenance, args.output)
    model_rows(args.artifacts, eda, args.output)
    configuration_rows(args.artifacts, args.output)


if __name__ == "__main__":
    main()
